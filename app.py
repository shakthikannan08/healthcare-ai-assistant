def disease_prediction(symptoms):
    if not symptoms.strip():
        return "Please enter some symptoms first."

    messages = [
        {"role": "system", "content": SYSTEM_PROMPT},
        {"role": "user", "content": (
            f"Symptoms: {symptoms}\n\n"
            "List the possible conditions these symptoms could point to, "
            "explain each briefly, and end with a short note on when to see a doctor. "
            "Do not give a diagnosis.\n\n"
            "IMPORTANT: End your response with a bold 'Urgency Level:' followed by Low, Medium, or High (See Doctor Now) based on the symptoms."
        )}
    ]
    return generate_response(messages, max_tokens=3000)

def clear_pred():
    return "", ""

# -------------------------------
# TREATMENT PLAN
# -------------------------------
def treatment_plan(condition, age, gender, history, height_cm, weight_kg):
    if not condition.strip():
        return "Please enter a condition first.", None

    bmi_line = ""
    bmi_instruction = ""
    if height_cm and weight_kg and height_cm > 0 and weight_kg > 0:
        bmi = weight_kg / ((height_cm / 100) ** 2)
        bmi_line = f"\nHeight: {height_cm} cm\nWeight: {weight_kg} kg\nBMI: {bmi:.1f}"
        bmi_instruction = " Factor the BMI into the lifestyle advice."

    messages = [
        {"role": "system", "content": SYSTEM_PROMPT},
        {"role": "user", "content": (
            f"Condition: {condition}\n"
            f"Age: {age}\n"
            f"Gender: {gender}\n"
            f"Medical History: {history}"
            f"{bmi_line}\n\n"
            "Give a clear treatment overview using a markdown tabular column for the main points. "
            "Then, add some lifestyle advice and warning signs below the table."
            f"{bmi_instruction}"
        )}
    ]
    reply = generate_response(messages, max_tokens=3000)
    return reply, create_pdf(reply)

