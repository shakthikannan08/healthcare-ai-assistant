def generate_response(messages, max_tokens=3000):
    try:
        response = client.chat.completions.create(
            model=MODEL_NAME,
            messages=messages,
            max_completion_tokens=max_tokens,
            temperature=0.7,
            top_p=0.9,
        )
        return response.choices[0].message.content.strip()
    except Exception as e:
        return f"⚠️ Groq API error: {type(e).__name__}: {e}"

# -------------------------------
# PATIENT CHAT
# -------------------------------
def patient_chat(history_state, user_input):
    if not user_input.strip():
        return history_state, render_chat(history_state), ""

    history_state = history_state + [{"role": "user", "content": user_input}]
    messages = [{"role": "system", "content": SYSTEM_PROMPT}] + history_state

    reply = generate_response(messages, max_tokens=3000)
    history_state = history_state + [{"role": "assistant", "content": reply}]

    return history_state, render_chat(history_state), ""

def regenerate_chat(history_state):
    if len(history_state) < 2:
        return history_state, render_chat(history_state)

    if history_state[-1]["role"] == "assistant":
        history_state.pop()

    messages = [{"role": "system", "content": SYSTEM_PROMPT}] + history_state
    reply = generate_response(messages, max_tokens=3000)
    history_state = history_state + [{"role": "assistant", "content": reply}]

    return history_state, render_chat(history_state)

def render_chat(history_state):
    lines = []
    for msg in history_state:
        speaker = "**Patient:**" if msg["role"] == "user" else "**AI:**"
        lines.append(f"{speaker} {msg['content']}")
    return "\n\n---\n\n".join(lines)

def clear_chat():
    return [], "", ""

