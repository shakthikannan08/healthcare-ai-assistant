# PDF EXPORT HELPER
# -------------------------------
def clean_text_for_pdf(text):
    lines = text.split('\n')
    final_lines = []
    in_table = False
    headers = []

    for line in lines:
        if '|' in line and '-' in line and not any(c.isalpha() for c in line):
            continue
        elif '|' in line:
            cells = [c.strip() for c in line.split('|') if c.strip()]
            if not in_table:
                headers = cells
                in_table = True
            else:
                for i, cell in enumerate(cells):
                    head = headers[i] if i < len(headers) else ""
                    if head and cell:
                        final_lines.append(f"- {head}: {cell}")
                    elif cell:
                        final_lines.append(f"- {cell}")
                final_lines.append("")
        else:
            in_table = False
            final_lines.append(line)

    out = '\n'.join(final_lines)
    out = re.sub(r'<abbr title="([^"]+)">([^<]+)</abbr>', r'\2 (\1)', out)
    out = re.sub(r'\*\*(.*?)\*\*', r'\1', out)
    out = out.replace("#", "")
    out = re.sub(r'<[^>]+>', '', out)

    return out.encode('latin-1', 'ignore').decode('latin-1')

def create_pdf(text):
    if not text or text.strip() == "":
        return None

    pdf = FPDF()
    pdf.add_page()
    pdf.set_font("Arial", 'B', 16)
    pdf.cell(0, 10, "Treatment Plan Details", ln=True, align='C')
    pdf.ln(5)
    pdf.set_font("Arial", size=12)
    safe_text = clean_text_for_pdf(text)
    pdf.multi_cell(0, 8, txt=safe_text)

    temp_pdf = tempfile.NamedTemporaryFile(delete=False, suffix=".pdf")
    pdf.output(temp_pdf.name)
    return temp_pdf.name

